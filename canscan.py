#!/usr/bin/env python3
'''
canscan.py - find the Voltwerk inverter on the CAN bus - generated by Claude Code

Layout of the 29-bit CAN ID (details in README.md):
  bit 28..24  0x0F         fixed prefix
  bit 23      1 = request, 0 = response
  bit 22..14  register     36 freq, 39 voltage, 40 current, 41 power
  bit 13..7   destination address
  bit  6..0   source address
Example, master 1 and inverter 3:
  request  0x0f89c181 = reg 39, dst 3, src 1 (we / display)
  response 0x0f09c083 = reg 39, dst 1, src 3 (inverter)

Phase 1 listens passively, phase 2 sends a read request (data 0x20, same
as voltwerk2mqtt.py) to every destination address and waits for an answer.
Stop voltwerk2mqtt before scanning:  sudo systemctl stop voltwerk2mqtt
'''

import argparse
import json
import subprocess
import sys
import time

import can

PREFIX = 0x0F
REQUEST_BIT = 1 << 23
READ_CMD = [0x20]

REGISTERS = {      # register: (name, multiplier, unit)
    36: ('freq', 64, 'Hz'),
    39: ('voltage', 256, 'V'),
    40: ('current', 16, 'A'),
    41: ('power', 4, 'kW'),
}


def make_id(reg, dst, src, request=True):
  return (PREFIX << 24) | (REQUEST_BIT if request else 0) | (reg << 14) | (dst << 7) | src


def parse_id(arb_id):
  if arb_id >> 24 != PREFIX:
    return None
  return {'request': bool(arb_id & REQUEST_BIT),
          'reg': (arb_id >> 14) & 0x1FF,
          'dst': (arb_id >> 7) & 0x7F,
          'src': arb_id & 0x7F}


def decode_value(data, multiplier):
  # same as voltwerk2mqtt.py: 16 bit little endian, signed, scaled by 1/0x2000
  if len(data) < 2:
    return None
  raw = data[1] << 8 | data[0]
  if raw & 0x8000:
    return -((((~raw) & 0x7fff) + 1) / 0x2000) * multiplier
  return ((raw & 0x7fff) / 0x2000) * multiplier


def describe(msg):
  text = f'ID 0x{msg.arbitration_id:08x} {"ext" if msg.is_extended_id else "std"} ' \
         f'DLC {msg.dlc} data {bytes(msg.data).hex() or "-"}'
  if msg.is_error_frame:
    return text + '  <ERROR FRAME>'
  p = parse_id(msg.arbitration_id) if msg.is_extended_id else None
  if p:
    kind = 'request ' if p['request'] else 'response'
    text += f'  -> {kind} reg {p["reg"]:3d} dst {p["dst"]:3d} src {p["src"]:3d}'
    if not p['request'] and p['reg'] in REGISTERS:
      name, mult, unit = REGISTERS[p['reg']]
      value = decode_value(msg.data, mult)
      if value is not None:
        text += f'  {name} = {value:.2f} {unit}'
  return text


def bus_state(channel):
  # state and error counters of the socketcan interface, e.g. ERROR-PASSIVE rx 132
  try:
    out = subprocess.run(['ip', '-details', '-json', 'link', 'show', channel],
                         capture_output=True, text=True, timeout=5).stdout
    info = json.loads(out)[0]['linkinfo']['info_data']
    berr = info.get('berr_counter', {})
    return f'{info.get("state", "?")} (tx errors {berr.get("tx", "?")}, rx errors {berr.get("rx", "?")}, ' \
           f'bitrate {info.get("bittiming", {}).get("bitrate", "?")})'
  except Exception as e:
    return f'unknown ({e})'


def parse_range(text):
  values = []
  for part in text.split(','):
    if '-' in part:
      lo, hi = part.split('-')
      values.extend(range(int(lo, 0), int(hi, 0) + 1))
    else:
      values.append(int(part, 0))
  if any(v < 0 or v > 127 for v in values):
    raise argparse.ArgumentTypeError('addresses must be 0..127')
  return values


def listen(bus, seconds):
  print(f'== phase 1: listening passively for {seconds} s')
  seen = {}
  end = time.monotonic() + seconds
  while time.monotonic() < end:
    msg = bus.recv(timeout=max(0.0, end - time.monotonic()))
    if msg is None:
      break
    key = (msg.arbitration_id, msg.is_error_frame)
    if key not in seen:
      print('  ' + describe(msg))
    seen[key] = seen.get(key, 0) + 1
  if not seen:
    print('  no traffic (inverter off, or bus/bitrate problem)')
  else:
    print(f'  {sum(seen.values())} frames, {len(seen)} different IDs')
  return seen


def ask(bus, reg, dst, src, timeout):
  '''send one read request, return (answers from dst, other frames)'''
  while bus.recv(timeout=0) is not None:    # drop old frames
    pass
  bus.send(can.Message(arbitration_id=make_id(reg, dst, src), is_extended_id=True, data=READ_CMD))
  hits, others = [], []
  end = time.monotonic() + timeout
  while time.monotonic() < end:
    msg = bus.recv(timeout=max(0.0, end - time.monotonic()))
    if msg is None:
      break
    p = parse_id(msg.arbitration_id) if msg.is_extended_id and not msg.is_error_frame else None
    if p and not p['request'] and p['reg'] == reg and p['src'] == dst and p['dst'] == src:
      hits.append(msg)
    else:
      others.append(msg)
  return hits, others


def scan(bus, reg, dsts, srcs, timeout, stop_on_hit):
  print(f'== phase 2: read reg {reg} from dst {dsts[0]}..{dsts[-1]} '
        f'with src {srcs[0]}..{srcs[-1]}, {len(dsts) * len(srcs)} requests')
  found = []
  for src in srcs:
    for dst in dsts:
      hits, others = ask(bus, reg, dst, src, timeout)
      for msg in others:
        print(f'  [dst {dst:3d} src {src:3d}] other frame: ' + describe(msg))
      if hits:
        print(f'  [dst {dst:3d} src {src:3d}] HIT: ' + describe(hits[0]))
        found.append((dst, src))
        if stop_on_hit:
          return found
    print(f'  src {src:3d} done')
  return found


def confirm(bus, dst, src, timeout):
  print(f'== phase 3: read all known registers from dst {dst} with src {src}')
  for reg in REGISTERS:
    hits, _ = ask(bus, reg, dst, src, timeout)
    print(f'  reg {reg}: ' + (describe(hits[0]) if hits else 'no answer'))
  print('  for voltwerk2mqtt.py:')
  for reg in (39, 40, 41, 36):
    print(f'    request 0x{make_id(reg, dst, src):08x} -> response 0x{make_id(reg, src, dst, request=False):08x}'
          f'  ({REGISTERS[reg][0]})')


def service_active():
  r = subprocess.run(['systemctl', 'is-active', '--quiet', 'voltwerk2mqtt'])
  return r.returncode == 0


def main(argv=None):
  ap = argparse.ArgumentParser(description='Scan for the Voltwerk inverter CAN address')
  ap.add_argument('--channel', default='can0')
  ap.add_argument('--interface', default='socketcan')
  ap.add_argument('--listen', type=float, default=10, help='seconds of passive listening first (0 = skip)')
  ap.add_argument('--reg', type=int, default=39, help='register to read (default 39 = voltage)')
  ap.add_argument('--dst', type=parse_range, default=parse_range('0-127'), help='destination addresses, e.g. 0-127 or 2,3')
  ap.add_argument('--src', type=parse_range, default=parse_range('1'), help='own source addresses, e.g. 1 or 0-127')
  ap.add_argument('--timeout', type=float, default=0.3, help='seconds to wait for an answer per request')
  ap.add_argument('--all', action='store_true', help='do not stop at the first hit')
  ap.add_argument('--force', action='store_true', help='scan even if voltwerk2mqtt is running')
  args = ap.parse_args(argv)

  if args.interface == 'socketcan':
    if service_active() and not args.force:
      sys.exit('voltwerk2mqtt is running - stop it first: sudo systemctl stop voltwerk2mqtt')
    print('bus state before: ' + bus_state(args.channel))

  with can.Bus(channel=args.channel, interface=args.interface) as bus:
    try:
      if args.listen > 0:
        listen(bus, args.listen)
      found = scan(bus, args.reg, args.dst, args.src, args.timeout, not args.all)
      if found:
        confirm(bus, *found[0], args.timeout)
      else:
        print('== no answer from any address')
    except KeyboardInterrupt:
      print('\naborted')
      found = []

  if args.interface == 'socketcan':
    print('bus state after:  ' + bus_state(args.channel))
  return 0 if found else 1


if __name__ == '__main__':
  sys.exit(main())
